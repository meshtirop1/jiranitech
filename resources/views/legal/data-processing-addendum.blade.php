                        <li style="font-size:.92rem;color:var(--ink-2)">Technical and organisational security measures, listed specifically</li>
                        <li style="font-size:.92rem;color:var(--ink-2)">Terms governing sub-processors, including authorisation and change notification</li>
                        <li style="font-size:.92rem;color:var(--ink-2)">Assistance with data subject rights requests</li>
                        <li style="font-size:.92rem;color:var(--ink-2)">Assistance with breach notification, impact assessments and prior consultation</li>
                        <li style="font-size:.92rem;color:var(--ink-2)">Deletion or return of personal data at the end of the engagement</li>
                        <li style="font-size:.92rem;color:var(--ink-2)">Audit and inspection rights</li>
                        <li style="font-size:.92rem;color:var(--ink-2)">Cross-border transfer mechanism where data leaves Kenya</li>
                    </ul>
